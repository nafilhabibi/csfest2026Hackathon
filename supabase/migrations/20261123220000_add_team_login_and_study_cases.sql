begin;

alter table public.users
    add column if not exists login_name text;

update public.users
set login_name = lower(btrim(coalesce(nullif(btrim(login_name), ''), name)));

do $$
begin
    if exists (
        select 1
        from public.users
        where login_name is null or btrim(login_name) = ''
    ) then
        raise exception 'Cannot create team login names: one or more users have an empty name.';
    end if;

    if exists (
        select lower(login_name)
        from public.users
        group by lower(login_name)
        having count(*) > 1
    ) then
        raise exception 'Cannot create unique team login names: duplicate names exist in public.users. Rename the duplicate teams, then rerun this migration.';
    end if;
end;
$$;

alter table public.users
    alter column login_name set not null,
    alter column email drop not null,
    add column if not exists role text not null default 'participant',
    add column if not exists theme_id bigint;

create unique index if not exists users_login_name_unique
    on public.users (login_name);

create table if not exists public.themes (
    id bigint generated by default as identity primary key,
    title text not null,
    description text,
    created_at timestamptz not null default timezone('utc', now()),
    updated_at timestamptz not null default timezone('utc', now())
);

create unique index if not exists themes_title_unique
    on public.themes (lower(title));

alter table public.users
    drop constraint if exists users_theme_id_fkey,
    drop constraint if exists users_role_check;

alter table public.users
    add constraint users_theme_id_fkey
        foreign key (theme_id) references public.themes(id) on delete set null,
    add constraint users_role_check
        check (role in ('admin', 'participant', 'judge'));

alter table public.users enable row level security;
alter table public.themes enable row level security;

create or replace function public.set_themes_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = timezone('utc', now());
    return new;
end;
$$;

drop trigger if exists set_themes_updated_at on public.themes;

create trigger set_themes_updated_at
before update on public.themes
for each row
execute function public.set_themes_updated_at();

commit;
